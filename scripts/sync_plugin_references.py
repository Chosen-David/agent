LINK_RE = re.compile(r"(!?\[[^\]]*\]\()([^)]+)(\))")


def _rewrite_target(source: str, target: str) -> str:
    target = target.strip()
    if target.startswith(("http://", "https://", "mailto:", "#", "data:")):
        return target
    if " " in target and not target.startswith("<"):
        # Avoid rewriting markdown targets with optional titles.
        return target
    raw = target[1:-1] if target.startswith("<") and target.endswith(">") else target
    path, sep, anchor = raw.partition("#")
    resolved = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
    if resolved.startswith("../"):
        return target
    url = REPO_BLOB + resolved + (("#" + anchor) if sep else "")
    return "<" + url + ">" if target.startswith("<") else url


def render(source: str) -> str:
    text = (ROOT / source).read_text(encoding="utf-8")
    text = LINK_RE.sub(lambda m: m.group(1) + _rewrite_target(source, m.group(2)) + m.group(3), text)
    return GENERATED + text


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated references are stale")
    args = parser.parse_args()
    stale = []
    for source, destinations in MAPPINGS.items():
        expected = render(source)
        for destination in destinations:
            path = ROOT / destination
            actual = path.read_text(encoding="utf-8") if path.exists() else None
            if actual == expected:
                continue
            stale.append(destination)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding="utf-8")
    if args.check and stale:
        print("stale generated references:")
        for item in stale:
            print(" -", item)
        return 1
    if stale and not args.check:
        print("updated", len(stale), "generated references")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
