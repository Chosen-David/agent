import posixpath
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO_BLOB = "https://github.com/Chosen-David/agent/blob/main/"
GENERATED = "<!-- GENERATED by scripts/sync_plugin_references.py; edit the source workflow instead. -->\n\n"

